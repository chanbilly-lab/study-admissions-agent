import { afterEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount, type VueWrapper } from '@vue/test-utils'
import PrivacyPanel from '../src/features/privacy/PrivacyPanel.vue'
import AuthView from '../src/features/auth/AuthView.vue'
import { PrivacyError } from '../src/features/privacy/client'
import { actor, otherActor, admission, allowed, declared, notice, privacyApi } from './privacyFixtures'

let wrapper: VueWrapper | undefined
afterEach(() => wrapper?.unmount())

describe('explicit privacy panel', () => {
  it('shows an unready notice and product limits without accepting age or consent', async () => {
    wrapper = mount(PrivacyPanel, { props: { actor, api: privacyApi({ notice: vi.fn(async () => notice({ is_synthetic: false, readiness: false, readiness_reason: 'processing_disabled', notice_id: null, notice_version: null })), admission: vi.fn(async () => admission({ readiness: false, reason: 'processing_disabled' })) }) } })
    await flushPromises()
    expect(wrapper.text()).toContain('正式告知尚未就绪')
    expect(wrapper.text()).toContain('尚未实现')
    expect(wrapper.text()).toContain('10 MiB')
    expect(wrapper.find('form').exists()).toBe(false)
    expect(wrapper.find('input').exists()).toBe(false)
    expect(wrapper.find('[data-testid="privacy-demo"]').exists()).toBe(false)
  })
  it('supports anonymous policy reading without requiring personal fields', async () => {
    wrapper = mount(PrivacyPanel, { props: { actor: null, api: privacyApi() } })
    await flushPromises()
    expect(wrapper.text()).toContain('公开浏览无需提交年龄或成绩')
    expect(wrapper.find('input').exists()).toBe(false)
    expect(wrapper.find('form').exists()).toBe(false)
  })
  it('renders notice text escaped and uses the server version/hash', async () => {
    const text = '<img src=x onerror="alert(1)">DEMO原文'
    wrapper = mount(PrivacyPanel, { props: { actor, api: privacyApi({ notice: vi.fn(async () => notice({ text })) }) } })
    await flushPromises()
    expect(wrapper.get('[data-testid="notice-text"]').text()).toBe(text)
    expect(wrapper.find('[data-testid="notice-text"] img').exists()).toBe(false)
    expect(wrapper.get('[data-testid="notice-hash"]').text()).toBe('a'.repeat(64))
    expect(wrapper.text()).toContain('DEMO_notice_v1')
  })
  it('requires adult radio and explicit confirmation before submitting, then a separate purpose check', async () => {
    const api = privacyApi()
    wrapper = mount(PrivacyPanel, { props: { actor, api } })
    await flushPromises()
    expect(wrapper.get('[data-testid="declare-age"]').attributes('disabled')).toBeDefined()
    expect(wrapper.find('[data-testid="core-confirmation"]').exists()).toBe(false)
    await wrapper.get('input[value="18_plus"]').setValue(true)
    expect(wrapper.get('[data-testid="declare-age"]').attributes('disabled')).toBeDefined()
    await wrapper.get('[data-testid="age-confirmation"]').setValue(true)
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(api.declareAge).toHaveBeenCalledTimes(1)
    expect(wrapper.get('[data-testid="age-assurance"]').text()).toContain('本人声明，未独立核验')
    expect(wrapper.get('[data-testid="admission-decision"]').text()).toContain('尚未确认核心咨询用途')
    expect(wrapper.get('[data-testid="core-confirmation"]').element).toHaveProperty('checked', false)
    await wrapper.get('[data-testid="core-confirmation"]').setValue(true)
    await wrapper.findAll('form')[1].trigger('submit')
    await flushPromises()
    expect(api.confirmCore).toHaveBeenCalledTimes(1)
    expect(wrapper.get('[data-testid="admission-decision"]').text()).toContain('私有业务仍未开放')
    expect(wrapper.find('[data-testid="withdraw-core"]').exists()).toBe(true)
    expect(wrapper.find('input[type="date"]').exists()).toBe(false)
    expect(wrapper.find('input[type="file"]').exists()).toBe(false)
  })
  it.each(['unknown', 'under_14', '14_17'])('never gives %s an optimistic permission', async (band) => {
    const api = privacyApi({ declareAge: vi.fn(async () => admission({ revision: 1 })) })
    wrapper = mount(PrivacyPanel, { props: { actor, api } })
    await flushPromises()
    await wrapper.get(`input[value="${band}"]`).setValue(true)
    expect(wrapper.get('[data-testid="admission-decision"]').text()).toContain('私有处理关闭')
    await wrapper.get('[data-testid="age-confirmation"]').setValue(true)
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(wrapper.get('[data-testid="age-assurance"]').text()).toContain('未知')
    expect(wrapper.find('[data-testid="core-confirmation"]').exists()).toBe(false)
    expect(wrapper.find('input[name="guardian"]').exists()).toBe(false)
  })
  it('leaves withdrawal available even while new collection is disabled', async () => {
    const api = privacyApi({ notice: vi.fn(async () => notice({ readiness: false, readiness_reason: 'processing_disabled' })), admission: vi.fn(async () => allowed({ readiness: false, reason: 'processing_disabled', core_consultation_allowed: false })) })
    wrapper = mount(PrivacyPanel, { props: { actor, api } })
    await flushPromises()
    expect(wrapper.find('form').exists()).toBe(false)
    await wrapper.get('[data-testid="withdraw-core"]').trigger('click')
    await flushPromises()
    expect(api.withdraw).toHaveBeenCalledTimes(1)
    expect(wrapper.text()).toContain('后续相应用途处理关闭')
  })
  it('clears radio and checkboxes on actor change', async () => {
    const api = privacyApi({ admission: vi.fn().mockResolvedValueOnce(declared()).mockResolvedValueOnce(admission({ user_id: otherActor.user_id })) })
    wrapper = mount(PrivacyPanel, { props: { actor, api } })
    await flushPromises()
    await wrapper.get('input[value="18_plus"]').setValue(true)
    await wrapper.get('[data-testid="age-confirmation"]').setValue(true)
    await wrapper.get('[data-testid="core-confirmation"]').setValue(true)
    await wrapper.setProps({ actor: otherActor })
    await flushPromises()
    expect(wrapper.get('input[value="18_plus"]').element).toHaveProperty('checked', false)
    expect(wrapper.get('[data-testid="age-confirmation"]').element).toHaveProperty('checked', false)
    expect(wrapper.find('[data-testid="core-confirmation"]').exists()).toBe(false)
  })
  it('shows a current 403 refusal without pretending consent succeeded', async () => {
    const api = privacyApi({ admission: vi.fn(async () => declared()), confirmCore: vi.fn().mockRejectedValue(new PrivacyError(403)) })
    wrapper = mount(PrivacyPanel, { props: { actor, api } })
    await flushPromises()
    await wrapper.get('[data-testid="core-confirmation"]').setValue(true)
    await wrapper.findAll('form')[1].trigger('submit')
    await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toContain('未获准')
    expect(wrapper.find('[data-testid="admission-decision"]').exists()).toBe(false)
  })
  it('distinguishes a stored active consent from usable admission after declaration expiry', async () => {
    wrapper = mount(PrivacyPanel, { props: { actor, api: privacyApi({ admission: vi.fn(async () => allowed({ core_consultation_allowed: false, reason: 'age_expired' })) }) } })
    await flushPromises()
    expect(wrapper.text()).toContain('已记录确认')
    expect(wrapper.text()).not.toContain('当前有效')
    expect(wrapper.get('[data-testid="admission-decision"]').text()).toContain('已到期')
    expect(wrapper.find('[data-testid="withdraw-core"]').exists()).toBe(true)
  })
  it('invalidates the parent session on a current privacy 401', async () => {
    const api = { loginPath: '/api/v2/auth/login', session: vi.fn(async () => actor), csrf: vi.fn(async () => ({ csrf_token: 'T'.repeat(43), expires_at: actor.expires_at })), logout: vi.fn(async () => ({ logged_out: true as const })) }
    wrapper = mount(AuthView, { props: { api, privacyApi: privacyApi({ admission: vi.fn().mockRejectedValue(new PrivacyError(401)) }) } })
    await flushPromises()
    expect(wrapper.find('[data-testid="actor-id"]').exists()).toBe(false)
    expect(wrapper.find('a.auth-login').exists()).toBe(true)
    expect(wrapper.find('form').exists()).toBe(false)
  })
})
